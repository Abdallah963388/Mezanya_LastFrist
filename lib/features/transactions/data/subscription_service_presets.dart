SubscriptionServicePreset? subscriptionPresetById(String? id) {
  if (id == null || id.isEmpty) return null;
  for (final preset in subscriptionServicePresets) {
    if (preset.id == id) {
      return preset;
    }
  }
  return null;
}

SubscriptionServicePreset? subscriptionPresetByName(String? name) {
  final normalized = name?.trim().toLowerCase();
  if (normalized == null || normalized.isEmpty) return null;
  for (final preset in subscriptionServicePresets) {
    if (preset.name.trim().toLowerCase() == normalized) {
      return preset;
    }
  }
  return null;
}
